"""Generate the Mathlib-only single-file version `lean4web/Fisher41Lean4Web.lean`.

The file concatenates, in dependency order, the Tau Ceti modules used by the proof (taken from
`lean/.lake/packages/TauCeti`, Apache 2.0) and every module of `lean/Fisher41`. Imports and
module-system markers are removed, and each source is wrapped in its own `section ... end` so that
its `open`, `variable` and unclosed `noncomputable section` commands stay local.
Run from the repository root after building `lean/`: `python3 lean/scripts/make_lean4web.py`.
"""

from pathlib import Path
import re
import subprocess

LEAN = Path(__file__).absolute().parents[1]
ROOT = LEAN.parent
OUTPUT = ROOT / "lean4web" / "Fisher41Lean4Web.lean"
TAUCETI = LEAN / ".lake" / "packages" / "TauCeti"

IMPORT = re.compile(r"^(?:public\s+)?(?:meta\s+)?import\s+(\S+)\s*$", re.M)
DROP = re.compile(r"^(?:module|(?:@\[expose\]\s+)?public(?:\s+meta)?\s+section)\s*$")
OPEN_SCOPE = re.compile(r"^(?:noncomputable\s+)?section(?:\s+(\S+))?\s*$|^namespace\s+(\S+)\s*$")
END_SCOPE = re.compile(r"^end(?:\s+(\S+))?\s*$")


def source_path(module):
    parts = module.split(".")
    if parts[0] == "Fisher41":
        return LEAN.joinpath(*parts).with_suffix(".lean")
    if parts[0] == "TauCeti":
        return TAUCETI.joinpath(*parts).with_suffix(".lean")
    return None


def strip_comments(line, depth):
    """Return the code part of `line` outside block comments, and the new comment depth."""
    code, i = [], 0
    while i < len(line):
        if line.startswith("/-", i):
            depth, i = depth + 1, i + 2
        elif depth and line.startswith("-/", i):
            depth, i = depth - 1, i + 2
        elif depth:
            i += 1
        elif line.startswith("--", i):
            break
        else:
            code.append(line[i])
            i += 1
    return "".join(code), depth


def localize(text):
    """Drop imports and module markers, and close every scope left open at the end."""
    lines, stack, depth = [], [], 0
    for line in text.splitlines():
        if depth == 0 and (IMPORT.match(line) or DROP.match(line)):
            continue
        code, depth_after = strip_comments(line, depth)
        if depth == 0:
            code = code.strip()
            opened, closed = OPEN_SCOPE.match(code), END_SCOPE.match(code)
            if opened:
                stack.append(opened.group(1) or opened.group(2))
            elif closed and stack:
                stack.pop()
        depth = depth_after
        lines.append(line)
    closing = ["end" + (" " + name if name else "") for name in reversed(stack)]
    return "\n".join(lines).strip() + ("\n\n" + "\n".join(closing) if closing else "")


def generate():
    visited, order, external = set(), [], set()

    def visit(module):
        if module in visited:
            return
        visited.add(module)
        path = source_path(module)
        if path is None:
            external.add(module)
            return
        text = path.read_text(encoding="utf-8")
        for dependency in IMPORT.findall(text):
            visit(dependency)
        order.append((module, path, text))

    visit("Fisher41")
    outside = sorted(m for m in external if not m.startswith("Mathlib"))
    if outside:
        raise SystemExit(f"Non-Mathlib external imports: {outside}")
    tauceti_rev = subprocess.run(["git", "rev-parse", "HEAD"], cwd=TAUCETI, text=True,
                                 capture_output=True).stdout.strip() or "unknown"
    imports = "\n".join(f"import {m}" for m in sorted(external))
    header = imports + f'''

/-!
# Fisher information along the heat flow is not convex: standalone Lean4Web proof

Generated by `lean/scripts/make_lean4web.py` from the complete proof in `lean/`.
Tested with Lean v4.35.0-rc3 and Mathlib 1b5006ca00888f8aaafa8939b28787d423e44bba.

It imports only the Mathlib modules imported by the original sources. The file contains, in dependency order, the parts of Tau Ceti used by the proof
(https://github.com/TauCetiProject/TauCeti, revision {tauceti_rev[:8]}, Apache 2.0,
copyright the Tau Ceti contributors) and every module of the project, including the 293
kernel-checked numerical cells. No project imports are needed.

Final theorems:
* `Fisher41.paperTheorem1` — Theorem 1 of the manuscript;
* `Fisher41.pdfMain`, `Fisher41.fisherSecondDerivNeg`, `Fisher41.fisherNonconvex`;
* `Arxiv.«2605.18081».fisherInformationConvexity` and its variant `.variants.smooth` — the
  Formal Conjectures targets.
-/

#eval Lean.versionString
'''
    body = "\n\n".join(
        f"-- Source: {module}\nsection\n\n{localize(text)}\n\nend"
        for module, _, text in order)
    footer = '''
#print axioms Fisher41.paperTheorem1
#print axioms Arxiv.«2605.18081».fisherInformationConvexity
#print axioms Arxiv.«2605.18081».fisherInformationConvexity.variants.smooth
'''
    content = header + "\n" + body + "\n" + footer
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    tau = sum(1 for m, _, _ in order if m.startswith("TauCeti"))
    print(f"Generated {OUTPUT.relative_to(ROOT)}: {len(order)} modules "
          f"({tau} from Tau Ceti), {len(content.splitlines())} lines")


if __name__ == "__main__":
    generate()
