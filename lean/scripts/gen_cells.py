"""Generate the kernel-checked cell certificate (Lean files) from a dyadic partition.

Mirrors `Fisher41/Numerics/Compute.lean` exactly (it uses verify/intervals.py with the
cube-root upper witness `⌊∛B⌋ + 1`), computes for every cell the smallest integer `q`
accepted by `cellCheck`, and writes
  Fisher41/Numerics/Cells/BlockNN.lean   (core-only; `blockCheck … = true := by decide +kernel`)
  Fisher41/Numerics/MainBound.lean       (assembly into a bound on the real integral)
Nothing here is trusted: Lean re-evaluates every cell in the kernel.

usage: python3 scripts/gen_cells.py data/partition_293.json 30 -5000000000000000000
"""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import intervals_ref as R
from intervals_ref import IV, Jet, S, radial

def cbrt_lean(self):            # Compute.lean: IV.cbrt?
    assert self.lo > 0
    a, b = R.icbrt(self.lo * S * S), R.icbrt(self.hi * S * S) + 1
    assert a ** 3 <= self.lo * S * S and self.hi * S * S <= b ** 3
    return IV(a, b)
IV.cbrt = cbrt_lean

D = 16384

def cell_q(A, B):
    left, right = IV.rat(A, D), IV.rat(B, D)
    mid = radial(Jet(IV.rat(A + B, 2 * D), IV.rat(1), IV.rat(0))).v.hi
    Bd = radial(Jet(IV(left.lo, right.hi), IV.rat(1), IV.rat(0))).e.abs_upper()
    h = B - A
    num = 12 * h * D * D * mid + h ** 3 * Bd
    den = 12 * S * D ** 3
    return -((-num) // den)

def main():
    part, block, target = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    ps = json.load(open(part))['endpoints_num_over_2pow14']
    assert ps[0] == 0 and ps[-1] == 8 * D and all(a < b for a, b in zip(ps, ps[1:]))
    qs = [cell_q(a, b) for a, b in zip(ps, ps[1:])]
    total = sum(qs)
    print(f'cells={len(qs)} sum(q)={total} target={target} ok={total <= target}')
    assert total <= target
    root = Path(__file__).resolve().parents[1]
    outdir = root / 'Fisher41' / 'Numerics' / 'Cells'
    outdir.mkdir(parents=True, exist_ok=True)
    for f in outdir.glob('*.lean'):
        f.unlink()
    cells = list(zip(ps, ps[1:], qs))
    blocks = [cells[i:i + block] for i in range(0, len(cells), block)]
    hdr = '/- Generated by scripts/gen_cells.py from {}; do not edit. -/\n'.format(Path(part).name)
    for k, bl in enumerate(blocks):
        # (1) kernel checks, core only
        out = [hdr + 'import Fisher41.Numerics.CellCheck\n', 'namespace Fisher41.Num.Cells\n']
        for j, (a, b, q) in enumerate(bl):
            idx = k * block + j
            out.append(f'theorem cell{idx:03d} : cellOK {a} {b} ({q}) = true := by decide +kernel\n')
        out.append('end Fisher41.Num.Cells\n')
        (outdir / f'Kernel{k:02d}.lean').write_text('\n'.join(out))
        # (2) real-number bound for the block
        s = sum(q for _, _, q in bl)
        a0, bN = bl[0][0], bl[-1][1]
        chain = f'(cellOK_sound Cells.cell{k * block:03d})'
        for j in range(1, len(bl)):
            chain = f'(integral_le_add {chain}\n      (cellOK_sound Cells.cell{k * block + j:03d}))'
        out = [hdr + 'import Fisher41.Numerics.Certificate\n'
               f'import Fisher41.Numerics.Cells.Kernel{k:02d}\n',
               'namespace Fisher41.Num\n',
               f'/-- Block {k}: cells {k * block}–{k * block + len(bl) - 1}. -/',
               f'theorem block{k:02d}_le :',
               f'    ∫ x in (({a0} : ℕ) : ℝ) / (D : ℝ)..(({bN} : ℕ) : ℝ) / (D : ℝ), radialC2.f x ≤',
               f'      (({s} : ℤ) : ℝ) := by',
               f'  refine le_trans {chain} (le_of_eq ?_)',
               '  norm_num\n',
               'end Fisher41.Num\n']
        (outdir / f'Block{k:02d}.lean').write_text('\n'.join(out))
    # (3) assembly
    lines = [hdr + 'import Fisher41.Numerics.Certificate']
    lines += [f'import Fisher41.Numerics.Cells.Block{k:02d}' for k in range(len(blocks))]
    lines += ['', '/-!', f'# The certified bound on the radial integral ({len(qs)} cells)', '-/', '',
              'namespace Fisher41.Num', '',
              f'/-- **Stage A (computational core).** `∫₀⁸ F ≤ {target}` for the radial integrand',
              '`F = radialC2.f`, from the kernel-checked cells. -/',
              f'theorem integral_radial_le : ∫ x in (0 : ℝ)..8, radialC2.f x ≤ ({target} : ℝ) := by']
    chain = 'block00_le'
    for k in range(1, len(blocks)):
        chain = f'(integral_le_add {chain} block{k:02d}_le)'
    lines.append(f'  have hall := {chain}')
    lines.append('  have h0D : ((0 : ℕ) : ℝ) / (D : ℝ) = 0 := by simp')
    lines.append(f'  have h8D : (({8 * D} : ℕ) : ℝ) / (D : ℝ) = 8 := by norm_num [D]')
    lines.append('  rw [h0D, h8D] at hall')
    lines.append('  refine hall.trans ?_')
    lines.append('  norm_num')
    lines += ['', 'end Fisher41.Num', '']
    (root / 'Fisher41' / 'Numerics' / 'MainBound.lean').write_text('\n'.join(lines))
    print('blocks:', len(blocks))

main()
